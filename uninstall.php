<?php
/**
 * Uninstall handler — runs on manual plugin deletion.
 *
 * Removes the drop-ins, the WP_CACHE constant (only the line Cosmic added),
 * every option/transient/cron the plugin owns, and the plugin's own cache
 * directory tree (single-site and multisite layouts, combined/ assets,
 * web-access guards, orphan .tmp files and empty dirs).
 *
 * @package cosmic-cache
 */

defined( 'WP_UNINSTALL_PLUGIN' ) || exit;

if ( ! defined( 'WP_CONTENT_DIR' ) ) {
	define( 'WP_CONTENT_DIR', ABSPATH . 'wp-content' );
}

/**
 * Recursively remove a directory tree without ever following a symlink out of
 * it: a symlink (including one masquerading as a dir) is unlinked, not
 * descended into.
 *
 * @param string $dir
 * @return void
 */
function cosmic_cache_uninstall_delete_tree( string $dir ): void {
	if ( is_link( $dir ) || ! is_dir( $dir ) ) {
		return;
	}
	foreach ( (array) scandir( $dir ) as $item ) {
		if ( '.' === $item || '..' === $item ) {
			continue;
		}
		$path = $dir . '/' . $item;
		if ( is_link( $path ) || ! is_dir( $path ) ) {
			@unlink( $path );
		} else {
			cosmic_cache_uninstall_delete_tree( $path );
		}
	}
	@rmdir( $dir );
}

/**
 * Drop-in cleanup: remove only when generated by Cosmic Cache.
 *
 * @param string $file
 * @param string $marker Substring that proves Cosmic wrote it.
 * @return void
 */
function cosmic_cache_uninstall_dropin( string $file, string $marker ): void {
	if ( ! is_file( $file ) || is_link( $file ) ) {
		return;
	}
	$contents = (string) file_get_contents( $file );
	if ( false !== strpos( $contents, $marker ) ) {
		@unlink( $file );
	}
}

cosmic_cache_uninstall_dropin( WP_CONTENT_DIR . '/advanced-cache.php', 'Cosmic Cache — advanced-cache drop-in' );
cosmic_cache_uninstall_dropin( WP_CONTENT_DIR . '/object-cache.php', 'COSMIC_CACHE_GENERATED' );

// Remove the WP_CACHE define only if it is the line Cosmic added (anchored to
// our marker comment) — never an unrelated WP_CACHE the operator keeps.
$wp_config = ABSPATH . 'wp-config.php';
if ( is_file( $wp_config ) && ! is_link( $wp_config ) && is_writable( $wp_config ) ) {
	$config = (string) file_get_contents( $wp_config );
	$config = preg_replace(
		'~\R?\s*define\s*\(\s*[\'"]WP_CACHE[\'"]\s*,\s*true\s*\)\s*;\s*//\s*Added by Cosmic Cache\s*$~mi',
		'',
		$config
	) ?? $config;
	@file_put_contents( $wp_config, $config );
}

// Cache root (respect the override constant).
if ( defined( 'COSMIC_CACHE_DIR' ) && COSMIC_CACHE_DIR ) {
	$cache_root = rtrim( COSMIC_CACHE_DIR, '/\\' );
} else {
	$cache_root = WP_CONTENT_DIR . '/cache/cosmic';
}

cosmic_cache_uninstall_delete_tree( $cache_root );

// Plugin options, transient notice and cron events.
foreach ( array( 'cosmic_cache_settings', 'cosmic_cache_owns_wp_cache', 'cosmic_cache_write_failures', 'cosmic_cache_schema_version', 'cosmic_cache_critical_stale', 'cosmic_cache_critical_meta', 'cosmic_cache_critical_draft', 'cosmic_cache_critical_prev' ) as $option ) {
	if ( function_exists( 'delete_option' ) ) {
		delete_option( $option );
	}
}
if ( function_exists( 'delete_transient' ) ) {
	delete_transient( 'cosmic_cache_notice' );
	delete_transient( 'cosmic_cache_preload_lock' );
	delete_transient( 'cosmic_cache_preload_queue' );
	delete_transient( 'cosmic_cache_preload_done' );
	delete_transient( 'cosmic_cache_robots_txt' );
}
foreach ( array( 'cosmic_cache_cleanup', 'cosmic_cache_preload' ) as $event ) {
	if ( function_exists( 'wp_clear_scheduled_hook' ) ) {
		wp_clear_scheduled_hook( $event );
	}
}
